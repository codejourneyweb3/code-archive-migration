-- ========== Access RPCs ==========
create or replace function public.school_has_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.user_roles where role = 'admin')
$$;
grant execute on function public.school_has_admin() to anon, authenticated;

create or replace function public.check_invite(_code text)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.invite_codes
    where upper(code) = upper(trim(_code)) and not is_used and (expires_at is null or expires_at > now()))
$$;
grant execute on function public.check_invite(text) to anon, authenticated;

create or replace function public.claim_first_admin()
returns boolean language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then return false; end if;
  perform pg_advisory_xact_lock(424242);
  if exists (select 1 from public.user_roles where role = 'admin') then return false; end if;
  insert into public.user_roles (user_id, role) values (auth.uid(), 'admin') on conflict do nothing;
  update public.profiles set allowed_pages = null where id = auth.uid();
  return true;
end $$;
grant execute on function public.claim_first_admin() to authenticated;

create or replace function public.redeem_invite(_code text)
returns boolean language plpgsql security definer set search_path = public as $$
declare inv public.invite_codes;
begin
  if auth.uid() is null then return false; end if;
  select * into inv from public.invite_codes
    where upper(code) = upper(trim(_code)) and not is_used and (expires_at is null or expires_at > now())
    for update;
  if not found then return false; end if;
  insert into public.user_roles (user_id, role) values (auth.uid(), inv.role) on conflict do nothing;
  update public.profiles set allowed_pages = nullif(inv.allowed_pages, '') where id = auth.uid();
  update public.invite_codes set is_used = true, used_by = auth.uid() where id = inv.id;
  return true;
end $$;
grant execute on function public.redeem_invite(text) to authenticated;

create or replace function public.claim_legacy_account()
returns boolean language plpgsql security definer set search_path = public as $$
declare u record; lu public.legacy_users; matches int;
begin
  if auth.uid() is null then return false; end if;
  select id, email, email_confirmed_at into u from auth.users where id = auth.uid();
  if u.email is null or u.email_confirmed_at is null then return false; end if;
  select count(*) into matches from public.legacy_users where lower(email) = lower(u.email) and claimed_by is null;
  if matches <> 1 then return false; end if;
  select * into lu from public.legacy_users where lower(email) = lower(u.email) and claimed_by is null for update;
  insert into public.user_roles (user_id, role) values (auth.uid(), lu.role) on conflict do nothing;
  update public.profiles set legacy_user_id = lu.legacy_id,
    full_name = case when full_name = '' then lu.full_name else full_name end,
    allowed_pages = nullif(lu.allowed_pages, '')
    where id = auth.uid();
  update public.legacy_users set claimed_by = auth.uid(), claimed_at = now() where legacy_id = lu.legacy_id;
  return true;
end $$;
grant execute on function public.claim_legacy_account() to authenticated;

create or replace function public.set_active_term(_term_id bigint)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.has_role(auth.uid(), 'admin') then raise exception 'Only administrators can change the active term'; end if;
  update public.terms set is_active = (id = _term_id) where true;
end $$;
grant execute on function public.set_active_term(bigint) to authenticated;

